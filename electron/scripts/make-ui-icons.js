'use strict';

// Writes static/js/core/icon-data.js: the Phosphor icons the app draws, as
// inline SVG markup. Run by hand after adding an icon to the catalog or to
// UI_ICONS below, and commit the result. The app never fetches an icon.
//
//   node scripts/make-ui-icons.js
//
// Every icon is the regular weight, with no fill layer. Phosphor Icons are MIT licensed
// (https://phosphoricons.com); the license travels in the generated header.

const fs = require('fs');
const path = require('path');

const Catalog = require('../../static/js/sim/catalog.js');

const ASSETS = path.join(__dirname, '..', 'node_modules', '@phosphor-icons', 'core', 'assets');
const OUT = path.join(__dirname, '..', '..', 'static', 'js', 'core', 'icon-data.js');

// Chrome icons, by Phosphor name.
const UI_ICONS = [
    'plus', 'minus', 'x', 'trash', 'copy', 'magnifying-glass', 'caret-down', 'caret-right',
    'caret-left', 'caret-up', 'arrow-counter-clockwise', 'arrow-clockwise', 'corners-out',
    'gear-six', 'folder', 'export', 'download-simple', 'upload-simple', 'lock-key',
    'lock-key-open', 'warning', 'warning-circle', 'info', 'check', 'check-circle',
    'dots-three', 'pencil-simple', 'arrow-right', 'chart-line', 'chart-bar', 'table',
    'sidebar-simple', 'link-simple', 'flow-arrow', 'file-plus', 'calendar-blank',
    'magnifying-glass-plus', 'magnifying-glass-minus', 'sparkle', 'tray', 'chart-line-up',
    'squares-four', 'cursor-click', 'hand-grabbing', 'eye', 'clock-counter-clockwise',
    'arrows-out-simple', 'shield-check', 'plugs-connected',
];

// Each asset is one <svg> of <path d="…"/> elements. Anything
// else means Phosphor changed shape and this script needs a look, so fail.
const SVG_RE = /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 256 256" fill="currentColor">((?:<path d="[-0-9.,A-Za-z ]+"\/>)+)<\/svg>\s*$/;

function inner(name) {
    const file = path.join(ASSETS, 'regular', `${name}.svg`);
    const svg = fs.readFileSync(file, 'utf8');
    const m = SVG_RE.exec(svg);
    if (!m) throw new Error(`unexpected markup in ${path.basename(file)}`);
    return m[1];
}

function main() {
    const moduleIcons = new Set([
        ...Catalog.PRESETS.map((p) => p.icon),
        ...Catalog.CATEGORIES.flatMap((c) => [c.icon, ...c.icons]),
    ]);
    const regular = {};
    for (const name of [...new Set([...moduleIcons, ...UI_ICONS])].sort()) regular[name] = inner(name);

    const header = [
        "'use strict';",
        '',
        '// GENERATED by electron/scripts/make-ui-icons.js. Do not edit by hand.',
        '//',
        '// Phosphor Icons, https://phosphoricons.com. MIT License,',
        '// Copyright (c) 2020 Phosphor Icons. Inner SVG markup on a 256 viewBox;',
        '// core/icons.js wraps it.',
        '',
    ].join('\n');
    const body = `window.CITRINE_ICON_DATA = ${JSON.stringify({ regular }, null, 1)};\n`;
    fs.writeFileSync(OUT, header + body);
    console.log(`wrote ${path.relative(process.cwd(), OUT)}: ${Object.keys(regular).length} icons`);
}

main();
